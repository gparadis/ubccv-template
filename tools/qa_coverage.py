#!/usr/bin/env python3
"""Check that data/ accounts for everything in your original Word CV.

Compares the token multiset of every paragraph/table cell in the Word dump
(build/cv_blocks.json, produced by `make blocks`) against the token multiset of
data/*.yaml plus data/publications.bib. Any token the original has more often
than the sources do is reported as potential data loss. This is formatting
agnostic, so it catches dropped authors, dates and amounts without caring how
they are laid out.

Use this while you migrate from Word: whenever it reports a token you have not
deliberately dropped, add the missing content to data/.
"""

from __future__ import annotations

import json
import re
from collections import Counter

import yaml

BLOCKS = "build/cv_blocks.json"

TOKEN_RE = re.compile(r"[0-9]+(?:[.,][0-9]+)*|[^\W\d_]+", re.UNICODE)
# Structural noise that intentionally disappears, plus template boilerplate:
# headings, table headers and connective text that the template regenerates.
