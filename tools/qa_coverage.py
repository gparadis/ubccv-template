# Tokens you have deliberately not carried over into data/ (duplicated header
# blocks, repaired typos, wording the template regenerates differently, ...).
# Add to this dict only after verifying each one is benign.
EXPECTED: dict[str, int] = {}

LIST_NUM_RE = re.compile(r"^\s*\d+\s*[.)]\s+")


def tokens(text: str) -> Counter:
    return Counter(
        t.lower() for t in TOKEN_RE.findall(text) if t.lower() not in IGNORE and len(t) > 1
    )


def source_tokens() -> Counter:
    total = Counter()
    for path in (
        "data/profile.yaml",
        "data/teaching.yaml",
        "data/research.yaml",
        "data/service.yaml",
        "data/awards.yaml",
        "data/other.yaml",
    ):
        with open(path, encoding="utf-8") as fh:
            total += tokens(yaml.safe_dump(yaml.safe_load(fh), allow_unicode=True))
    with open("data/publications.bib", encoding="utf-8") as fh:
        total += tokens(fh.read())
    return total


def docx_tokens() -> Counter:
    with open(BLOCKS, encoding="utf-8") as fh:
        blocks = json.load(fh)
    total = Counter()
    for b in blocks:
        if b["type"] == "p":
            # list numbering is regenerated at render time, not stored
            total += tokens(LIST_NUM_RE.sub("", b["text"]))
        else:
            for row in b["rows"]:
                for c in row:
                    total += tokens(c["text"])
    return total


def main() -> int:
    original, extracted = docx_tokens(), source_tokens()
    missing = Counter()
    for tok, n in original.items():
        gap = n - extracted.get(tok, 0) - EXPECTED.get(tok, 0)
        if gap > 0:
            missing[tok] = gap
    if not missing:
        print(
            f"coverage: OK -- every token in the Word CV is accounted for "
            f"({len(EXPECTED)} known exception(s))"
        )
        return 0
    print(f"coverage: {len(missing)} unexpected token(s) missing from data/\n")
    for tok, n in missing.most_common(60):
        print(f"  {n:>3}x  {tok}")
    print(
        "\nAdd the missing content to data/, or record an intentional exception "
        "in EXPECTED at the top of tools/qa_coverage.py."
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
